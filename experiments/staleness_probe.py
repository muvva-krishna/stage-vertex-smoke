STOP = {"a","an","and","after","are","as","at","by","for","from","in","is","it","of","on","or","the","to","when","while","with","without","user","current","old","trace","reaches","revision","rev","investigation","blamed","during","before","ends","keep","keep","appearing","application"}


def tokens(text: str) -> list[str]:
    return [t for t in re.findall(r"[a-z0-9_]+", text.lower()) if len(t) > 1 and t not in STOP]


def rank_files(files: dict[str, str], issue: str, evidence: list[str]) -> list[tuple[str, float]]:
    """Transparent term-overlap ranker; evidence text contributes one vote."""
    issue_terms = set(tokens(issue))
    evidence_terms = tokens(" ".join(evidence))
    scores = {}
    for path, summary in files.items():
        doc_terms = set(tokens(path + " " + summary))
        # Issue match is one vote per distinct term; each evidence mention is
        # retained, making repeated/long stale notes capable of dominating.
        scores[path] = sum(t in doc_terms for t in issue_terms) + sum(t in doc_terms for t in evidence_terms)
    return sorted(scores.items(), key=lambda item: (-item[1], item[0]))


def reciprocal_rank(ranking: list[tuple[str, float]], gold: str) -> float:
    for i, (path, _score) in enumerate(ranking, 1):
        if path == gold:
            return 1.0 / i
    return 0.0


def run() -> dict:
    trials = []
    methods = ("issue_only", "all_evidence", "revision_gated")
    conditions = ("clean", "stale_only", "fresh_plus_stale")
    for case in CASES:
        for condition in conditions:
            supplied = []
            metadata = []
            if condition in ("clean", "fresh_plus_stale"):
                supplied.append(case["fresh"])
                metadata.append({"text":case["fresh"], "revision":CURRENT_REV})
            if condition in ("stale_only", "fresh_plus_stale"):
                supplied.append(case["stale"])
                metadata.append({"text":case["stale"], "revision":OLD_REV})
            for method in methods:
                if method == "issue_only":
                    used = []
                elif method == "all_evidence":
                    used = supplied
                else:
                    used = [e["text"] for e in metadata if e["revision"] == CURRENT_REV]
                ranked = rank_files(case["files"], case["issue"], used)
                trials.append({
                    "case":case["id"], "condition":condition, "method":method,
                    "gold_file":case["gold"], "ranked_files":[p for p, _ in ranked],
                    "gold_rank":next(i for i,(p,_) in enumerate(ranked,1) if p == case["gold"]),
                    "reciprocal_rank":reciprocal_rank(ranked, case["gold"]),
                    "correct_at_1":ranked[0][0] == case["gold"],
                })
    cells = []
    grouped = defaultdict(list)
    for trial in trials:
        grouped[(trial["condition"], trial["method"])].append(trial)
    for (condition, method), rows in sorted(grouped.items()):
        cells.append({
            "condition":condition, "method":method, "n":len(rows),
            "top1_correct":sum(r["correct_at_1"] for r in rows),
            "top1_accuracy":round(sum(r["correct_at_1"] for r in rows)/len(rows), 3),
            "mean_reciprocal_rank":round(sum(r["reciprocal_rank"] for r in rows)/len(rows), 3),
        })
    # All methods use the same eight cases; issue_only is the no-evidence
    # baseline, regardless of the context condition being evaluated.
    baseline = next(c["top1_accuracy"] for c in cells
                    if c["condition"] == "clean" and c["method"] == "issue_only")
    deltas = []
    for condition in conditions:
        for method in methods:
            current = next(c["top1_accuracy"] for c in cells
                           if c["condition"] == condition and c["method"] == method)
            deltas.append({"condition":condition,"method":method,
                           "delta_top1_vs_issue_only":round(current-baseline,3)})
    return {
        "title":"Revision-aware filtering for stale debugging context",
        "date":"2026-11-01", "synthetic":True,
        "question":"Does filtering debugging evidence to the current code revision reduce file-localization errors from stale notes?",
        "design":{"cases":len(CASES),"conditions":list(conditions),"methods":list(methods),
                  "trials":len(trials),"scoring":"distinct issue-term overlap plus one vote per evidence-term occurrence; deterministic lexical ranking; ties broken by path",
                  "fresh_revision":CURRENT_REV,"stale_revision":OLD_REV},
        "cells":cells,"deltas_vs_issue_only":deltas,"trials":trials,
        "limitations":["All cases and evidence are synthetic and authored for this probe.",
                       "The ranker is a transparent lexical baseline, not an LLM or a coding agent.",
                       "This measures file localization only; it does not measure repair success or real-world prevalence.",
                       "The small constructed sample supports a reproducible demonstration, not a general claim."],
    }


def main() -> None:
    result = run()
    RESULT_PATH.parent.mkdir(parents=True, exist_ok=True)
    RESULT_PATH.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {RESULT_PATH.relative_to(ROOT)} ({result['design']['trials']} trials)")
    for row in result["cells"]:
        print(f"{row['condition']:18} {row['method']:14} top1={row['top1_correct']}/{row['n']} ({row['top1_accuracy']:.3f}) MRR={row['mean_reciprocal_rank']:.3f}")
    for row in result["deltas_vs_issue_only"]:
        print(f"delta {row['condition']:18} {row['method']:14} {row['delta_top1_vs_issue_only']:+.3f}")


if __name__ == "__main__":
    main()
